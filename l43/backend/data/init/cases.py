async def init_case_precedent_data(graph_repository):
    for case in CASE_PRECEDENT_ENTITIES:
        try:
            await graph_repository.create_entity("CasePrecedent", {
                "id": case["id"],
                "name": case["name"],
                "content": case["content"],
                "case_number": case["case_number"],
                "court": case["court"],
                "judgment_date": case["judgment_date"],
                "case_type": case["case_type"],
                "verdict": case["verdict"],
                "facts": case["facts"],
                "relevant_laws": str(case.get("relevant_laws", []))
            })
        except Exception as e:
            print(f"创建判例实体失败 {case['id']}: {e}")

    for rel in CASE_RELATIONS:
        try:
            await graph_repository.create_relation(
                source_id=rel["source"],
                source_label="CasePrecedent",
                target_id=rel["target"],
                target_label="LAW",
                rel_type=rel["type"],
                properties=rel.get("props", {})
            )
        except Exception as e:
            print(f"创建判例关系失败 {rel['source']}->{rel['target']}: {e}")

    print(f"判例数据初始化完成: {len(CASE_PRECEDENT_ENTITIES)}个判例, {len(CASE_RELATIONS)}条关系")
