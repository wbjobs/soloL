async def init_civil_code_data(graph_repository) -> Dict[str, int]:
    node_count = 0
    relation_count = 0
    for article in _ARTICLES:
        props = {
            "id": article[0],
            "name": article[1],
            "content": article[2],
            "category": article[3],
            "article_number": article[4],
        }
        try:
            await graph_repository.create_entity("LAW", props)
            node_count += 1
        except Exception:
            pass
    for relation in _RELATIONS:
        try:
            await graph_repository.create_relation(
                source_id=relation[0],
                source_label="LAW",
                target_id=relation[1],
                target_label="LAW",
                rel_type=relation[2],
                properties={"description": relation[3]},
            )
            relation_count += 1
        except Exception:
            pass
    return {"nodes": node_count, "relations": relation_count}