def _build_law_entities() -> List[Dict[str, Any]]:
    entities = []
    for category, articles in _LAW_RAW.items():
        for art_num, name, content in articles:
            entities.append({
                "id": f"law_{art_num}",
                "name": name,
                "content": content,
                "category": category,
                "article_number": f"第{art_num}条",
            })
    return entities


